--  22 — משימות מערכת: client_id אופציונלי
-- ═══════════════════════════════════════════════════════════════════════════
--  משימת בדיקת העדכניות הרבעונית אינה שייכת ללקוח. עד היום client_id היה
--  NOT NULL עם FK ללקוחות; מתירים NULL (ה-FK ממשיך לחול על ערכים שאינם NULL).
--  באפליקציה: clientId='system' ממופה ל-NULL בכתיבה ובחזרה בקריאה.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.tasks alter column client_id drop not null;

-- רשת ביטחון נגד כפילות משימות מערכת (הרכבה כפולה בפיתוח / שני מכשירים):
-- לאותו משתמש לא ייווצרו שתי משימות מערכת עם אותה כותרת (הכותרת כוללת את תג הרבעון).
create unique index if not exists tasks_system_unique_title
  on public.tasks (user_id, title) where client_id is null;
