-- 129 — מקף רגיל גם בנתונים ההיסטוריים
--
-- ‼ מיגרציה 128 יישרה את תוויות החומרים בלבד. כאן משלימים את השאר: גוף
-- המכתב, הנושא, כותרות המשנה שהלקוח רואה בדף האישי, שמות המסמכים שהמערכת
-- יצרה — ו**גם העותקים של מיילים שכבר נשלחו** (הכרעת גיא 2026-08-24).
--
-- ‼ מה שצריך לדעת על העותקים השמורים: email_messages.html הוא הארכיון של מה
-- שיצא בפועל, והוא מה ש"צפייה במייל" מציגה. אחרי המיגרציה הזו העותק אצלנו
-- יראה "-" בעוד שההודעה שיושבת בתיבה של הנמען עדיין נושאת "—". זה שינוי
-- תצוגתי בלבד ואינו נוגע במשמעות, אבל הוא כן אומר שהארכיון אינו זהה תו-בתו
-- למה שנשלח. גיא ביקש זאת במפורש.
--
-- ‼ storage_path של מסמכים אינו נגזר מהשם (הוא לפי מזהה), ולכן שינוי
-- file_name הוא תצוגה בלבד ואינו מנתק שום קובץ. כל 14 השמות נוצרו על ידי
-- המערכת (ייפוי כוח, הסכם התקשרות, מכתבים) — אף אחד מהם לא הוקלד על ידי אדם.

-- ─── 1. עותקי המיילים שנשלחו ────────────────────────────────────────────────
UPDATE public.email_messages
   SET html = replace(html, '—', '-')
 WHERE html LIKE '%—%';

UPDATE public.email_messages
   SET subject = replace(subject, '—', '-')
 WHERE subject LIKE '%—%';

-- ─── 2. טקסט חי בשלבי הקליטה ────────────────────────────────────────────────
-- ‼ החלפה על ה-payload כולו ולא מפתח-מפתח: הסקר הראה שהמפתחות היחידים
-- שנושאים "—" הם טקסט תצוגה (releaseBody / releaseSubject / releaseDraft /
-- releaseHistory / clientSub), ואף שם-מפתח אינו מכיל את התו. כך גם ערכים
-- מקוננים מטופלים בלי לפספס.
UPDATE public.onboarding_steps
   SET payload = replace(payload::text, '—', '-')::jsonb
 WHERE payload::text LIKE '%—%';

-- ─── 3. שמות מסמכים שהמערכת יצרה ────────────────────────────────────────────
UPDATE public.documents
   SET file_name = replace(file_name, '—', '-')
 WHERE file_name LIKE '%—%';
