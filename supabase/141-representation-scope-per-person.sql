-- 141 — הייצוג הוא רשות × אדם, וההיקף נשמר על הבקשה
--
-- עד כה הייצוג נשאל "אילו רשויות לתא המשפחתי". זה נכון למס הכנסה, שבו יש תיק
-- אחד למשק הבית, אבל לא למע"מ ולניכויים: שם התיק שייך לאדם. ייתכן שרק לבן/בת
-- הזוג יש תיק מע"מ שצריך לייצג כדי לסגור אותו, וייתכן שלשניהם — ואז אלה שתי
-- בקשות רישום נפרדות בשע״ם.
--
-- (א) `authority_representations[<רשות>].targets` — מערך של 'client'/'spouse',
--     למע"מ ולניכויים בלבד. ‼ **היעדרו = ['client']**, שזו בדיוק המשמעות של
--     כל בקשה שנוצרה עד היום. אין מילוי-לאחור ואין פרשנות-מחדש.
--
-- (ב) `representation_requests.scope` — תמונת ההיקף שהתבקש, נכתבת פעם אחת
--     ביצירת הבקשה. זהו מקור האמת ל"מה ביקשנו ולמי": המרשם שבכרטיס ממשיך לזוז
--     עם הזמן, ו-`tax_files` מתאר תיקים בפועל שגם הם משתנים. בקשה שנפתחת
--     אחרי חודש חייבת להראות מה התבקש אז, לא מה נכון היום.
--     חסר ⇒ בקשה מלפני המהלך; המסך נופל למרשם של הכרטיס, כמו קודם.
--
-- (ג) `execution.shaamEntries` — מפה של הזנות שע״ם נוספות לפי `<רשות>:<אדם>`
--     (למשל `vat:spouse`). מס הכנסה נשאר ב-`execution.incomeTax` כי הוא הגשה
--     אחת למשק הבית ושם חי מחזור בן-הזוג-הרשום. JSON בתוך עמודה קיימת —
--     בקשה ישנה בלי המפה מציגה בדיוק את מה שהציגה קודם.
--
-- אין DDL על (א) ו-(ג): שניהם מפתחות בתוך jsonb קיים.

alter table public.representation_requests
  add column if not exists scope jsonb;

comment on column public.representation_requests.scope is
  'ההיקף שהתבקש: רשות → {status, level, targets[]}. תמונה היסטורית, נכתבת פעם אחת. NULL = בקשה מלפני מיגרציה 141.';
