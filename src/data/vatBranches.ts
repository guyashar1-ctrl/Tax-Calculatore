export const licensedRuleOf = (code: string | undefined): LicensedRule | undefined => (code ? LICENSED_BY_BRANCH[code] : undefined);
export const branchName = (code: string | undefined): string => (code ? VAT_BRANCH_BY_CODE[code]?.name ?? '' : '');

/** חיפוש לפי קוד (תחילית) או מילה בשם (כל המילים). */
export function searchBranches(q: string, limit = 12): VatBranch[] {
  const t = q.trim();
  if (!t) return [];
  if (/^\d+$/.test(t)) return VAT_BRANCHES.filter(b => b.code.startsWith(t)).slice(0, limit);
  const words = t.split(/\s+/).filter(Boolean);
  return VAT_BRANCHES.filter(b => words.every(w => b.name.includes(w))).slice(0, limit);
}
