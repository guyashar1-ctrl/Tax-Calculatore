/** הלוח לשנה: של אותה שנה, אחרת האחרון שפורסם לפניה (או הראשון). */
export function tableFor(year: number): { table: LivingTable; exact: boolean } {
  const sorted = [...LIVING_TABLES].sort((a, b) => a.year - b.year);
  const exact = sorted.find(t => t.year === year);
  if (exact) return { table: exact, exact: true };
  const before = sorted.filter(t => t.year < year).pop();
  return { table: before ?? sorted[0], exact: false };
}

/** הוצאה לפי הלוח: קבוצת ההכנסה (1–10) ומספר הנפשות (1–6+). */
export function tableExpense(year: number, familyIncome: number, persons: number) {
  const { table, exact } = tableFor(year);
  const idx = table.upper.findIndex(u => familyIncome <= u);
  const group = idx < 0 ? 10 : idx + 1;
  const p = Math.min(6, Math.max(1, persons));
  return { amount: table.rows[group - 1][p - 1], group, persons: p, tableYear: table.year, exact, source: table.source };
}
