/** טביעת אצבע קצרה לטבלה — כדי שאפשר יהיה לדעת על איזו גרסת כללים הוצעה כל הצעה. */
export function rulesFingerprint(tsv = handbookTsv(OFFICE_HANDBOOK.rows)): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < tsv.length; i++) { h ^= tsv.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return (h >>> 0).toString(16).padStart(8, '0');
}

export function rulesVersionLabel(): string {
  return `${OFFICE_HANDBOOK.date} · ${OFFICE_HANDBOOK.rows.length} שורות · ${rulesFingerprint()}`;
}

