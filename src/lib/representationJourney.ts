/** השלב שבו נמצאת בקשה לפי הסטטוס שלה — לבדיקות ולמסכים שרוצים לשאול. */
export function repStageForStatus(status: RepresentationStatus): RepStage {
  const s = REP_STAGES.find(st => st.statuses?.includes(status));
  if (!s) throw new Error(`representation status without a stage: ${status}`);
  return s;
}

/**
 * מפת התהליך שהלקוח רואה בטופס הקליטה — נגזרת מאותה רשימה, בלי שלבי המשרד.
 * ‼ אותו סדר בדיוק כמו במשרד; ביטוח לאומי מופיע רק כשהוא כלול.
 */
export function customerProcessMap(opts: { niIncluded: boolean }): CustomerMilestone[] {
  return REP_STAGES
    .filter(s => s.customer && (!s.customer.onlyWhenNi || opts.niIncluded))
    .map(s => s.customer!);
}
