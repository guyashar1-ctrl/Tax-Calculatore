/** המדריך לפי המפתח שנשמר בבקשה. ‼ מפתח לא מוכר (או לא מחרוזת, או שם של תכונת אובייקט) ⇒ null. */
export function photoGuideFor(key: unknown): PhotoGuideDef | null {
  return typeof key === 'string' && Object.prototype.hasOwnProperty.call(PHOTO_GUIDES, key)
    ? PHOTO_GUIDES[key as PhotoGuideKey] : null;
}

/**
 * הנתיב היחסי של הצילום של צעד (מתחת ל-public). ‼ המספר הוא לפי הצילומים — צעד בלי צילום לא תופס
 * מספר, ולכן הצעד האחרון כאן (טופס 502, בלי צילום) אינו step-7. null ⇒ אין צילום לצעד הזה.
 */
export function photoGuideImagePath(g: PhotoGuideDef, stepIndex: number): string | null {
  if (!g.steps[stepIndex]?.image) return null;
  const n = g.steps.slice(0, stepIndex + 1).filter(s => s.image).length;
  return `guides/${g.dir}/step-${n}.webp`;
}

/** הכתובת של הצילום לדפדפן (כולל בסיס האתר). לצעד בלי צילום — מחרוזת ריקה, ואיש לא מבקש אותה. */
export const photoGuideImageUrl = (g: PhotoGuideDef, stepIndex: number): string => {
  const path = photoGuideImagePath(g, stepIndex);
  return path ? `${import.meta.env.BASE_URL}${path}` : '';
};
