// ─── סידור bidi של טקסט עברי/מעורב ב-PDF (utils/pdfHebrew.ts) ───────────────
// המחרוזת «הוויזואלית» כאן היא מה שהעין רואה משמאל לימין: מקטע עברי מתהפך
// (כמו ש-fontkit מצייר אותו), והשאר כמו שהוא.

import { test, equal, type TestCase } from '../../testkit/tinyTest';
import { layoutMixed } from '../pdfHebrew';

const visual = (s: string) => layoutMixed(s).map(seg => (seg.rtl ? [...seg.text].reverse().join('') : seg.text)).join('');

export const TESTS: TestCase[] = [
  test('סוגריים מתהפכים בהקשר עברי («(עמוד 4)» ולא «)עמוד 4(»)', () => {
    equal(visual('(עמוד 4)'), '(4 דומע)');
  }),
  test('נקודתיים אחרי מספר הן פיסוק של המשפט — נקראות אחרי המספר', () => {
    equal(visual('סעיף 3: עיסוק'), 'קוסיע :3 ףיעס');
  }),
  test('מפרידי מספר בתוך מספר נשארים חלק ממנו', () => {
    equal(visual('סכום 1,800.50 שקל'), 'לקש 1,800.50 םוכס');
    equal(visual('שעה 12:30'), '12:30 העש');
    equal(visual('לפחות 30% מהשכר'), 'רכשהמ 30% תוחפל');
  }),
  test('נקודה בסוף משפט שמסתיים במספר — בקצה השמאלי', () => {
    equal(visual('סכום 1,800.'), '.1,800 םוכס');
  }),
  test('מייל ומספר עם מקף נשארים יחידה אחת', () => {
    equal(visual('מייל: a.b-1@x.co.il'), 'a.b-1@x.co.il :ליימ');
    equal(visual('טלפון 050-1234567'), '050-1234567 ןופלט');
  }),
  test('טקסט בלי עברית לא נוגעים בו', () => {
    equal(visual('(06.2026) 6101'), '(06.2026) 6101');
  }),
];
