#!/usr/bin/env node
/**
 * staging-schema-extract.mjs — מייצר קובץ SQL שמשחזר את מבנה המסד של הפרודקשן.
 *
 * למה לא `supabase db dump`: הפקודה הזאת מריצה pg_dump בתוך Docker, ואין Docker
 * ולא כלי Postgres על המחשב הזה. במקום זה הסקריפט קורא את המבנה מהמסד עצמו
 * (pg_catalog / information_schema) דרך אותו Management API שכל שאר הסקריפטים
 * בפרויקט משתמשים בו — קריאה בלבד, בלי סיסמת מסד ובלי התקנות.
 *
 * הפלט אינו "כנראה נכון": אחריו רץ staging-schema-verify.mjs, שמריץ את אותן
 * שאילתות ספירה והשוואה על שתי הסביבות ומדפיס הפרש. מבנה שאינו זהה — נופל.
 *
 * שימוש:
 *   node scripts/staging-schema-extract.mjs [קובץ-פלט]
 * ברירת מחדל: supabase/staging/schema-from-prod.sql
 *
 * קריאה בלבד מהפרודקשן. אינו כותב דבר למסד.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PROD_REF = 'uoweoqtuiettozagwgdw';

const env = {};
for (const line of readFileSync(resolve(ROOT, '.env.local'), 'utf8').split(/\r?\n/)) {
  const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
  if (m) env[m[1]] = m[2].trim();
}
const TOKEN = env.SUPABASE_ACCESS_TOKEN;
if (!TOKEN) { console.error('✋ SUPABASE_ACCESS_TOKEN חסר ב-.env.local'); process.exit(1); }

async function q(sql) {
  const r = await fetch(`https://api.supabase.com/v1/projects/${PROD_REF}/database/query`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${TOKEN}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: sql }),
  });
  const text = await r.text();
  if (!r.ok) { console.error('✋ שאילתה נכשלה:', text.slice(0, 400)); process.exit(1); }
  return JSON.parse(text);
}

const out = [];
const section = (t) => out.push(`\n-- ═══ ${t} ${'═'.repeat(Math.max(0, 70 - t.length))}\n`);

out.push(`-- מבנה המסד של הפרודקשן (${PROD_REF}), נמשך בקריאה בלבד.`);
out.push(`-- נוצר ע"י scripts/staging-schema-extract.mjs. לא לערוך ידנית.`);
out.push(`-- היעד היחיד: פרויקט ה-staging. לעולם לא מורץ על הפרודקשן.`);

// ── הרחבות ──────────────────────────────────────────────────────────────────
// ברירת המחדל של פרויקט Supabase כוללת חלק מהן; if not exists מייתר בדיקה.
section('הרחבות');
for (const e of await q(`
  select e.extname, n.nspname as schema
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
   where e.extname not in ('plpgsql')
   order by 1`)) {
  out.push(`create extension if not exists "${e.extname}" with schema ${e.schema};`);
}

// ── רצפים ───────────────────────────────────────────────────────────────────
// חייבים לקדום לטבלאות: ברירות מחדל של עמודות מפנות אליהם ב-nextval.
section('רצפים');
for (const s of await q(`
  select sequencename from pg_sequences where schemaname = 'public' order by 1`)) {
  out.push(`create sequence if not exists public.${s.sequencename};`);
}

// ── טבלאות ──────────────────────────────────────────────────────────────────
// עמודות בלבד. מפתחות ואילוצים נוספים בהמשך, כדי שסדר הטבלאות לא ישבור FK.
section('טבלאות');
const cols = await q(`
  select c.relname as table_name, a.attname as column_name, a.attnum,
         format_type(a.atttypid, a.atttypmod) as type,
         a.attnotnull as not_null,
         pg_get_expr(d.adbin, d.adrelid) as default_expr,
         a.attidentity, a.attgenerated
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
   where n.nspname = 'public' and c.relkind = 'r'
   order by c.relname, a.attnum`);
const byTable = new Map();
for (const c of cols) {
  if (!byTable.has(c.table_name)) byTable.set(c.table_name, []);
  byTable.get(c.table_name).push(c);
}
for (const [table, list] of byTable) {
  const defs = list.map((c) => {
    let s = `  "${c.column_name}" ${c.type}`;
    if (c.attidentity === 'a') s += ' generated always as identity';
    else if (c.attidentity === 'd') s += ' generated by default as identity';
    else if (c.attgenerated === 's') s += ` generated always as (${c.default_expr}) stored`;
    else if (c.default_expr != null) s += ` default ${c.default_expr}`;
    if (c.not_null) s += ' not null';
    return s;
  });
  out.push(`create table if not exists public."${table}" (\n${defs.join(',\n')}\n);`);
}

// ── אילוצים ─────────────────────────────────────────────────────────────────
// p/u/c קודם, ואז f — מפתח זר דורש שהיעד כבר קיים עם מפתח ייחודי.
section('אילוצים');
const cons = await q(`
  select c.relname as table_name, con.conname, con.contype,
         pg_get_constraintdef(con.oid) as def
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and con.contype in ('p','u','c','f')
   order by case con.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 else 4 end,
            c.relname, con.conname`);
for (const c of cons) {
  // to_regclass מונע כפילות: האילוץ נוצר רק אם אין אחד בשם הזה.
  out.push(`do $$ begin
  if not exists (select 1 from pg_constraint where conname = '${c.conname}'
                   and conrelid = 'public."${c.table_name}"'::regclass) then
    alter table public."${c.table_name}" add constraint "${c.conname}" ${c.def};
  end if;
end $$;`);
}

// ── אינדקסים ────────────────────────────────────────────────────────────────
// האינדקסים שמגבים מפתח ראשי/ייחודי כבר נוצרו עם האילוץ, ולכן מסוננים.
section('אינדקסים');
for (const i of await q(`
  select indexdef from pg_indexes i
   where schemaname = 'public'
     and not exists (select 1 from pg_constraint con
                      where con.conname = i.indexname and con.contype in ('p','u'))
   order by indexname`)) {
  out.push(i.indexdef.replace(/^CREATE INDEX /i, 'CREATE INDEX IF NOT EXISTS ')
                     .replace(/^CREATE UNIQUE INDEX /i, 'CREATE UNIQUE INDEX IF NOT EXISTS ') + ';');
}

// ── פונקציות ────────────────────────────────────────────────────────────────
// פונקציית SQL נבדקת בזמן היצירה ולכן עשויה לדרוש פונקציה אחרת שקדמה לה.
// לכן היצירה עוברת בסבבים: כל סבב מנסה את מה שנכשל, עד שאין התקדמות.
section('פונקציות');
const fns = await q(`
  select p.proname, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind in ('f','p')
   order by p.proname`);
out.push('-- הרצה בסבבים — ראה staging-apply.mjs. כאן הן בסדר אלפביתי.');
for (const f of fns) out.push(f.def.trim().replace(/;?\s*$/, '') + ';');

// ── טריגרים ─────────────────────────────────────────────────────────────────
section('טריגרים');
for (const t of await q(`
  select c.relname as table_name, t.tgname, pg_get_triggerdef(t.oid) as def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and not t.tgisinternal
   order by c.relname, t.tgname`)) {
  out.push(`drop trigger if exists "${t.tgname}" on public."${t.table_name}";`);
  out.push(t.def + ';');
}

// ── RLS ─────────────────────────────────────────────────────────────────────
// בלי זה כל טבלה ב-staging הייתה פתוחה, והבדיקות היו עוברות מסיבה הלא נכונה.
section('RLS ומדיניות');
for (const r of await q(`
  select c.relname, c.relrowsecurity, c.relforcerowsecurity
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' and c.relrowsecurity
   order by 1`)) {
  out.push(`alter table public."${r.relname}" enable row level security;`);
  if (r.relforcerowsecurity) out.push(`alter table public."${r.relname}" force row level security;`);
}
for (const p of await q(`
  select tablename, policyname, permissive, roles, cmd, qual, with_check
    from pg_policies where schemaname = 'public'
   order by tablename, policyname`)) {
  const roles = (Array.isArray(p.roles) ? p.roles : String(p.roles || '').replace(/^\{|\}$/g, '').split(','))
    .map((x) => String(x).trim()).filter(Boolean);
  let s = `create policy "${p.policyname}" on public."${p.tablename}"`;
  s += ` as ${String(p.permissive).toLowerCase() === 'permissive' ? 'permissive' : 'restrictive'}`;
  s += ` for ${String(p.cmd).toLowerCase()}`;
  if (roles.length) s += ` to ${roles.map((r) => (r === 'public' ? 'public' : `"${r}"`)).join(', ')}`;
  if (p.qual != null) s += ` using (${p.qual})`;
  if (p.with_check != null) s += ` with check (${p.with_check})`;
  out.push(`drop policy if exists "${p.policyname}" on public."${p.tablename}";`);
  out.push(s + ';');
}

// ── הרשאות ──────────────────────────────────────────────────────────────────
section('הרשאות');
for (const g of await q(`
  select grantee, table_name, string_agg(distinct privilege_type, ', ') as privs
    from information_schema.role_table_grants
   where table_schema = 'public' and grantee in ('anon','authenticated','service_role')
   group by grantee, table_name order by table_name, grantee`)) {
  out.push(`grant ${g.privs.toLowerCase()} on public."${g.table_name}" to "${g.grantee}";`);
}
for (const g of await q(`
  select r.rolname as grantee, p.proname, pg_get_function_identity_arguments(p.oid) as args
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    cross join lateral (values ('anon'),('authenticated'),('service_role')) as v(rolname)
    join pg_roles r on r.rolname = v.rolname
   where n.nspname = 'public'
     and has_function_privilege(r.oid, p.oid, 'EXECUTE')
   order by p.proname, r.rolname`)) {
  out.push(`grant execute on function public."${g.proname}"(${g.args}) to "${g.grantee}";`);
}

// ── דליי אחסון ──────────────────────────────────────────────────────────────
// הקבצים עצמם אינם מועתקים — רק ההגדרות, כדי שהעלאה בבדיקה תמצא דלי.
section('דליי אחסון');
for (const b of await q(`
  select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by id`)) {
  const mime = b.allowed_mime_types
    ? `array[${(Array.isArray(b.allowed_mime_types) ? b.allowed_mime_types
        : String(b.allowed_mime_types).replace(/^\{|\}$/g, '').split(','))
        .map((m) => `'${String(m).trim()}'`).join(',')}]::text[]`
    : 'null';
  out.push(`insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('${b.id}', '${b.name}', ${b.public}, ${b.file_size_limit ?? 'null'}, ${mime})
on conflict (id) do nothing;`);
}
for (const p of await q(`
  select policyname, permissive, roles, cmd, qual, with_check
    from pg_policies where schemaname = 'storage' and tablename = 'objects'
   order by policyname`)) {
  const roles = (Array.isArray(p.roles) ? p.roles : String(p.roles || '').replace(/^\{|\}$/g, '').split(','))
    .map((x) => String(x).trim()).filter(Boolean);
  let s = `create policy "${p.policyname}" on storage.objects`;
  s += ` as ${String(p.permissive).toLowerCase() === 'permissive' ? 'permissive' : 'restrictive'}`;
  s += ` for ${String(p.cmd).toLowerCase()}`;
  if (roles.length) s += ` to ${roles.map((r) => (r === 'public' ? 'public' : `"${r}"`)).join(', ')}`;
  if (p.qual != null) s += ` using (${p.qual})`;
  if (p.with_check != null) s += ` with check (${p.with_check})`;
  out.push(`drop policy if exists "${p.policyname}" on storage.objects;`);
  out.push(s + ';');
}

// ── הערות ───────────────────────────────────────────────────────────────────
section('הערות עמודות');
for (const c of await q(`
  select c.relname as table_name, a.attname as column_name, d.description
    from pg_description d
    join pg_class c on c.oid = d.objoid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum = d.objsubid
   where n.nspname = 'public' and d.objsubid > 0
   order by c.relname, a.attnum`)) {
  out.push(`comment on column public."${c.table_name}"."${c.column_name}" is ${JSON.stringify(c.description).replace(/^"|"$/g, "'").replace(/\\"/g, '"')};`);
}

// ‼ משימות pg_cron אינן מועתקות בכוונה: תזכורות והגיבוי השבועי לא ירוצו
//   ב-staging. הפעלה שלהן שם הייתה שולחת מיילים בלי שאיש ביקש.
section('לא הועתק בכוונה');
out.push('-- pg_cron: 3 משימות בפרודקשן. אינן נוצרות ב-staging (תוכנית §14).');
out.push('-- vault: סודות אינם ניתנים לקריאה ונקבעים ידנית ב-staging.');
out.push('-- auth.users: משתמש הבדיקה נוצר ע"י seed-staging.mjs.');

const target = resolve(ROOT, process.argv[2] || 'supabase/staging/schema-from-prod.sql');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.join('\n') + '\n', 'utf8');
console.log(`✓ נכתב ${target}`);
console.log(`  טבלאות ${byTable.size} · פונקציות ${fns.length} · אילוצים ${cons.length}`);
